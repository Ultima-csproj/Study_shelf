CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 fixture_key TEXT UNIQUE, display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
 state TEXT NOT NULL CHECK (state IN ('active','disabled'))
);
CREATE TABLE user_platform_permissions (
 user_id BIGINT NOT NULL REFERENCES users(id),
 permission TEXT NOT NULL CHECK (permission = 'moderate_public_materials'),
 PRIMARY KEY (user_id,permission)
);
CREATE TABLE institutions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 fixture_key TEXT UNIQUE, name TEXT NOT NULL CHECK (length(btrim(name)) > 0)
);
CREATE TABLE institution_memberships (
 user_id BIGINT NOT NULL REFERENCES users(id), institution_id BIGINT NOT NULL REFERENCES institutions(id),
 state TEXT NOT NULL CHECK (state IN ('pending','active','rejected','revoked')), PRIMARY KEY (user_id,institution_id)
);
CREATE TABLE membership_academic_roles (
 user_id BIGINT NOT NULL, institution_id BIGINT NOT NULL, role TEXT NOT NULL CHECK (role IN ('student','teacher')),
 FOREIGN KEY (user_id,institution_id) REFERENCES institution_memberships(user_id,institution_id),
 PRIMARY KEY (user_id,institution_id,role)
);
CREATE TABLE membership_permissions (
 user_id BIGINT NOT NULL, institution_id BIGINT NOT NULL,
 permission TEXT NOT NULL CHECK (permission IN ('manage_members','manage_disciplines','create_materials','manage_materials')),
 FOREIGN KEY (user_id,institution_id) REFERENCES institution_memberships(user_id,institution_id),
 PRIMARY KEY (user_id,institution_id,permission)
);
CREATE TABLE contributors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 fixture_key TEXT UNIQUE, kind TEXT NOT NULL CHECK (kind IN ('person','organization')),
 display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
 user_id BIGINT REFERENCES users(id), institution_id BIGINT REFERENCES institutions(id),
 CHECK ((kind = 'person' AND institution_id IS NULL) OR (kind = 'organization' AND user_id IS NULL))
);
