CREATE TABLE materials (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 fixture_key TEXT UNIQUE, owner_user_id BIGINT REFERENCES users(id), owner_institution_id BIGINT REFERENCES institutions(id),
 created_by_user_id BIGINT NOT NULL REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL,
 visibility TEXT NOT NULL CHECK (visibility IN ('private','public')), published_revision_id BIGINT,
 first_published_at TIMESTAMPTZ,
 CHECK (num_nonnulls(owner_user_id,owner_institution_id) = 1),
 CHECK ((published_revision_id IS NULL) = (first_published_at IS NULL)),
 CHECK (first_published_at >= created_at)
);
CREATE TABLE material_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 material_id BIGINT NOT NULL REFERENCES materials(id), base_revision_id BIGINT,
 created_by_user_id BIGINT NOT NULL REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL CHECK (updated_at >= created_at),
 edit_version BIGINT NOT NULL DEFAULT 0 CHECK (edit_version >= 0),
 state TEXT NOT NULL CHECK (state IN ('draft','pending_moderation','published','rejected')),
 title TEXT NOT NULL CHECK (length(btrim(title)) > 0), description TEXT NOT NULL,
 material_type TEXT NOT NULL CHECK (material_type IN ('lecture','book','article','video','lab')),
 source_year INTEGER CHECK (source_year BETWEEN 1 AND 9999), preview_url TEXT,
 duration_seconds BIGINT CHECK (duration_seconds BETWEEN 0 AND 4294967295),
 file_size_bytes BIGINT CHECK (file_size_bytes >= 0),
 submitted_by_user_id BIGINT REFERENCES users(id), submitted_at TIMESTAMPTZ, published_at TIMESTAMPTZ,
 UNIQUE (material_id,id),
 FOREIGN KEY (material_id,base_revision_id) REFERENCES material_revisions(material_id,id),
 CHECK (base_revision_id <> id), CHECK (submitted_at BETWEEN created_at AND updated_at),
 CHECK (published_at >= submitted_at AND published_at = updated_at),
 CHECK (
  (state = 'draft' AND submitted_by_user_id IS NULL AND submitted_at IS NULL AND published_at IS NULL)
  OR (state IN ('pending_moderation','rejected') AND submitted_by_user_id IS NOT NULL AND submitted_at IS NOT NULL AND published_at IS NULL)
  OR (state = 'published' AND submitted_by_user_id IS NOT NULL AND submitted_at IS NOT NULL AND published_at IS NOT NULL)
 )
);
ALTER TABLE materials ADD CONSTRAINT materials_publication_fk FOREIGN KEY (id,published_revision_id) REFERENCES material_revisions(material_id,id);
CREATE INDEX material_revisions_material_idx ON material_revisions(material_id);
CREATE INDEX material_revisions_publication_idx ON material_revisions(published_at DESC,material_id) WHERE state = 'published';
CREATE TABLE revision_credits (
 revision_id BIGINT NOT NULL REFERENCES material_revisions(id), contributor_id BIGINT NOT NULL REFERENCES contributors(id),
 display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
 role TEXT NOT NULL CHECK (role IN ('author','co_author','editor','translator','lecturer','reviewer')),
 position INTEGER NOT NULL CHECK (position >= 0),
 PRIMARY KEY (revision_id,contributor_id,role), UNIQUE (revision_id,position)
);
CREATE TABLE revision_tags (
 revision_id BIGINT NOT NULL REFERENCES material_revisions(id),
 tag TEXT NOT NULL CHECK (length(btrim(tag)) BETWEEN 1 AND 80), position INTEGER NOT NULL CHECK (position >= 0),
 PRIMARY KEY (revision_id,tag), UNIQUE (revision_id,position)
);
CREATE TABLE revision_editors (
 revision_id BIGINT NOT NULL REFERENCES material_revisions(id), user_id BIGINT NOT NULL REFERENCES users(id),
 PRIMARY KEY (revision_id,user_id)
);
CREATE TABLE material_collaborators (
 material_id BIGINT NOT NULL REFERENCES materials(id), user_id BIGINT NOT NULL REFERENCES users(id),
 active BOOLEAN NOT NULL, PRIMARY KEY (material_id,user_id)
);
CREATE TABLE collaborator_permissions (
 material_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 permission TEXT NOT NULL CHECK (permission IN ('read','edit_revision','submit_for_moderation','manage_collaborators')),
 FOREIGN KEY (material_id,user_id) REFERENCES material_collaborators(material_id,user_id),
 PRIMARY KEY (material_id,user_id,permission)
);
CREATE TABLE moderation_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 revision_id BIGINT NOT NULL UNIQUE REFERENCES material_revisions(id), reviewer_id BIGINT NOT NULL REFERENCES users(id),
 decision TEXT NOT NULL CHECK (decision IN ('approved','rejected')), reason TEXT,
 reviewed_at TIMESTAMPTZ NOT NULL, was_self_review BOOLEAN NOT NULL,
 CHECK ((decision = 'approved' AND reason IS NULL) OR (decision = 'rejected' AND reason IS NOT NULL AND length(btrim(reason)) > 0))
);
