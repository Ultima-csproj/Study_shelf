CREATE TABLE disciplines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  fixture_key TEXT UNIQUE,
  institution_id BIGINT NOT NULL REFERENCES institutions (id),
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
  UNIQUE (id, institution_id)
);

CREATE TABLE discipline_placements (
  material_id BIGINT NOT NULL REFERENCES materials (id),
  discipline_id BIGINT NOT NULL,
  institution_id BIGINT NOT NULL,
  responsible_user_id BIGINT,
  course SMALLINT CHECK (course BETWEEN 1 AND 255),
  FOREIGN KEY (discipline_id, institution_id) REFERENCES disciplines (id, institution_id),
  FOREIGN KEY (responsible_user_id, institution_id) REFERENCES institution_memberships (user_id, institution_id),
  PRIMARY KEY (material_id, discipline_id)
);

CREATE INDEX discipline_placements_filter_idx ON discipline_placements (discipline_id, material_id);

CREATE INDEX discipline_placements_responsible_idx ON discipline_placements (responsible_user_id, material_id);

CREATE TABLE material_search (
  material_id BIGINT PRIMARY KEY REFERENCES materials (id),
  revision_id BIGINT NOT NULL,
  search_text TEXT NOT NULL,
  sort_title TEXT NOT NULL,
  FOREIGN KEY (material_id, revision_id) REFERENCES material_revisions (material_id, id)
);

CREATE VIEW public_materials AS
SELECT
  m.id,
  r.id AS published_revision_id,
  r.title,
  r.description,
  r.material_type,
  r.source_year,
  r.preview_url,
  r.duration_seconds,
  r.file_size_bytes,
  m.first_published_at,
  r.published_at
FROM
  materials m
  JOIN material_revisions r ON r.id = m.published_revision_id
  AND r.material_id = m.id
WHERE
  m.visibility = 'public'
  AND r.state = 'published';
