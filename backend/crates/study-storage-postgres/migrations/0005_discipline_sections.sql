CREATE TABLE discipline_sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discipline_id BIGINT NOT NULL REFERENCES disciplines (id),
  fixture_key TEXT UNIQUE,
  title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
  description TEXT NOT NULL DEFAULT '',
  position INTEGER NOT NULL CHECK (position > 0),
  UNIQUE (discipline_id, position),
  UNIQUE (id, discipline_id)
);

CREATE TABLE discipline_section_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discipline_id BIGINT NOT NULL,
  section_id BIGINT NOT NULL,
  placement_id BIGINT NOT NULL,
  position INTEGER NOT NULL CHECK (position > 0),
  FOREIGN KEY (section_id, discipline_id) REFERENCES discipline_sections (id, discipline_id),
  FOREIGN KEY (placement_id, discipline_id) REFERENCES discipline_placements (id, discipline_id),
  UNIQUE (section_id, position),
  UNIQUE (section_id, placement_id)
);

CREATE INDEX discipline_entries_parent_idx ON discipline_section_entries (discipline_id, section_id, position);

CREATE INDEX discipline_placements_material_idx ON discipline_placements (material_id, id);
