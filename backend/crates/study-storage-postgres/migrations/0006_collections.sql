CREATE TABLE collections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_key TEXT UNIQUE,
  slug TEXT NOT NULL UNIQUE CHECK (length(btrim(slug)) > 0),
  title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
  short_description TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  purpose TEXT NOT NULL DEFAULT '',
  target_audience TEXT NOT NULL DEFAULT '',
  owner_user_id BIGINT REFERENCES users (id),
  owner_institution_id BIGINT REFERENCES institutions (id),
  created_by_user_id BIGINT NOT NULL REFERENCES users (id),
  visibility TEXT NOT NULL CHECK (visibility IN ('private', 'public')),
  discipline_id BIGINT REFERENCES disciplines (id),
  course SMALLINT CHECK (course BETWEEN 1 AND 255),
  difficulty TEXT CHECK (
    difficulty IN ('beginner', 'intermediate', 'advanced')
  ),
  estimated_minutes INTEGER CHECK (estimated_minutes > 0),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL CHECK (updated_at >= created_at),
  CHECK (
    num_nonnulls (owner_user_id, owner_institution_id) = 1
  )
);

CREATE TABLE collection_participants (
  collection_id BIGINT NOT NULL REFERENCES collections (id),
  contributor_id BIGINT NOT NULL REFERENCES contributors (id),
  display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
  role TEXT NOT NULL CHECK (role IN ('author', 'curator', 'contributor')),
  position INTEGER NOT NULL CHECK (position > 0),
  PRIMARY KEY (collection_id, contributor_id, role),
  UNIQUE (collection_id, position)
);

CREATE TABLE collection_sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  collection_id BIGINT NOT NULL REFERENCES collections (id),
  title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
  description TEXT NOT NULL DEFAULT '',
  position INTEGER NOT NULL CHECK (position > 0),
  UNIQUE (collection_id, position),
  UNIQUE (id, collection_id)
);

CREATE TABLE collection_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  collection_id BIGINT NOT NULL,
  section_id BIGINT NOT NULL,
  material_id BIGINT NOT NULL REFERENCES materials (id),
  position INTEGER NOT NULL CHECK (position > 0),
  FOREIGN KEY (section_id, collection_id) REFERENCES collection_sections (id, collection_id),
  UNIQUE (section_id, position),
  UNIQUE (section_id, material_id)
);

CREATE INDEX collections_public_order_idx ON collections (created_at DESC, id)
WHERE
  visibility = 'public';

CREATE INDEX collection_entries_material_idx ON collection_entries (material_id);

CREATE INDEX collection_entries_parent_idx ON collection_entries (collection_id, section_id, position);
